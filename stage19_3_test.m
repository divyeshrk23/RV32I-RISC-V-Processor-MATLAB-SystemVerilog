function stage19_3_test

clc;

fprintf('\n');
fprintf('============================================================\n');
fprintf('             STAGE 19.3 - MEM TO EX FORWARDING\n');
fprintf('============================================================\n');

testsPassed = 0;
totalTests = 10;


% ============================================================
% TEST 1
% MEM/WB -> RS1
% ============================================================

result = mem_ex_forwarding( ...
    1, ...
    2, ...
    5, ...
    true, ...
    uint32(50), ...
    1, ...
    true, ...
    uint32(100));

if result.forwarding && ...
   result.rs1Forward && ...
   result.rs1Source == "MEM/WB" && ...
   result.rs1Value == uint32(100)

    fprintf('MEM/WB -> RS1 FORWARDING   : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('MEM/WB -> RS1 FORWARDING   : FAIL\n');

end


% ============================================================
% TEST 2
% MEM/WB -> RS2
% ============================================================

result = mem_ex_forwarding( ...
    3, ...
    2, ...
    5, ...
    true, ...
    uint32(50), ...
    2, ...
    true, ...
    uint32(200));

if result.forwarding && ...
   result.rs2Forward && ...
   result.rs2Source == "MEM/WB" && ...
   result.rs2Value == uint32(200)

    fprintf('MEM/WB -> RS2 FORWARDING   : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('MEM/WB -> RS2 FORWARDING   : FAIL\n');

end


% ============================================================
% TEST 3
% Both operands from MEM/WB
% ============================================================

result1 = mem_ex_forwarding( ...
    6, ...
    7, ...
    5, ...
    true, ...
    uint32(50), ...
    6, ...
    true, ...
    uint32(600));

result2 = mem_ex_forwarding( ...
    6, ...
    7, ...
    5, ...
    true, ...
    uint32(50), ...
    7, ...
    true, ...
    uint32(700));

if result1.rs1Forward && ...
   result1.rs1Value == uint32(600) && ...
   result2.rs2Forward && ...
   result2.rs2Value == uint32(700)

    fprintf('DUAL MEM/WB FORWARDING     : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('DUAL MEM/WB FORWARDING     : FAIL\n');

end


% ============================================================
% TEST 4
% EX/MEM must have priority over MEM/WB
% ============================================================

result = mem_ex_forwarding( ...
    5, ...
    8, ...
    5, ...
    true, ...
    uint32(500), ...
    5, ...
    true, ...
    uint32(400));

if result.rs1Forward && ...
   result.rs1Source == "EX/MEM" && ...
   result.rs1Value == uint32(500)

    fprintf('EX/MEM PRIORITY            : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('EX/MEM PRIORITY            : FAIL\n');

end


% ============================================================
% TEST 5
% No matching registers
% ============================================================

result = mem_ex_forwarding( ...
    1, ...
    2, ...
    3, ...
    true, ...
    uint32(30), ...
    4, ...
    true, ...
    uint32(40));

if ~result.forwarding

    fprintf('NO FORWARDING CASE         : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('NO FORWARDING CASE         : FAIL\n');

end


% ============================================================
% TEST 6
% x0 must never be forwarded
% ============================================================

result = mem_ex_forwarding( ...
    0, ...
    0, ...
    0, ...
    true, ...
    uint32(99), ...
    0, ...
    true, ...
    uint32(88));

if ~result.forwarding && ...
   ~result.rs1Forward && ...
   ~result.rs2Forward

    fprintf('x0 PROTECTION              : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('x0 PROTECTION              : FAIL\n');

end


% ============================================================
% TEST 7
% MEM/WB RegWrite disabled
% ============================================================

result = mem_ex_forwarding( ...
    9, ...
    10, ...
    3, ...
    false, ...
    uint32(30), ...
    9, ...
    false, ...
    uint32(90));

if ~result.forwarding

    fprintf('MEM/WB REGWRITE DISABLED   : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('MEM/WB REGWRITE DISABLED   : FAIL\n');

end


% ============================================================
% TEST 8
% EX/MEM absent, MEM/WB active
% ============================================================

result = mem_ex_forwarding( ...
    12, ...
    13, ...
    0, ...
    false, ...
    uint32(0), ...
    12, ...
    true, ...
    uint32(1200));

if result.rs1Forward && ...
   result.rs1Source == "MEM/WB" && ...
   result.rs1Value == uint32(1200)

    fprintf('MEM/WB ONLY FORWARDING     : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('MEM/WB ONLY FORWARDING     : FAIL\n');

end


% ============================================================
% TEST 9
% RS1 from EX/MEM
% RS2 from MEM/WB
% ============================================================

result = mem_ex_forwarding( ...
    14, ...
    15, ...
    14, ...
    true, ...
    uint32(1400), ...
    15, ...
    true, ...
    uint32(1500));

if result.rs1Source == "EX/MEM" && ...
   result.rs1Value == uint32(1400) && ...
   result.rs2Source == "MEM/WB" && ...
   result.rs2Value == uint32(1500)

    fprintf('MIXED FORWARDING SOURCES   : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('MIXED FORWARDING SOURCES   : FAIL\n');

end


% ============================================================
% TEST 10
% 32-bit value preservation
% ============================================================

value = uint32(hex2dec('FFFFFFFF'));

result = mem_ex_forwarding( ...
    20, ...
    21, ...
    4, ...
    false, ...
    uint32(0), ...
    20, ...
    true, ...
    value);

if result.rs1Forward && ...
   result.rs1Source == "MEM/WB" && ...
   result.rs1Value == value && ...
   isa(result.rs1Value,'uint32')

    fprintf('32-BIT VALUE PRESERVATION  : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('32-BIT VALUE PRESERVATION  : FAIL\n');

end


% ============================================================
% FINAL RESULTS
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('                  STAGE 19.3 RESULTS\n');
fprintf('============================================================\n');

fprintf('Tests passed : %d / %d\n', ...
    testsPassed,totalTests);

fprintf('============================================================\n');


% ============================================================
% PASS / FAIL
% ============================================================

if testsPassed == totalTests

    fprintf('\n');
    fprintf('********************************************\n');
    fprintf('       STAGE 19.3 PASSED!\n');
    fprintf('       MEM -> EX FORWARDING VERIFIED\n');
    fprintf('********************************************\n');

else

    fprintf('\n');
    fprintf('********************************************\n');
    fprintf('       STAGE 19.3 FAILED\n');
    fprintf('       CHECK RESULTS ABOVE\n');
    fprintf('********************************************\n');

end

end