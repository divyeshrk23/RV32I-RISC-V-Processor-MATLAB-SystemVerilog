function stage19_6_test

clc;

fprintf('\n');
fprintf('============================================================\n');
fprintf('       STAGE 19.6 - FORWARDING + STALL INTEGRATION\n');
fprintf('============================================================\n');

testsPassed = 0;
totalTests = 10;


% ============================================================
% TEST 1
%
% EX/MEM -> EX forwarding
% No load-use hazard.
% ============================================================

result = hazard_control( ...
    1, ...
    2, ...
    5, ...
    false, ...
    false, ...
    "NONE", ...
    1, ...
    true, ...
    uint32(100), ...
    0, ...
    false, ...
    uint32(0));

if result.forwarding && ...
   result.rs1Forward && ...
   result.rs1Source == "EX/MEM" && ...
   result.rs1Value == uint32(100) && ...
   ~result.stall

    fprintf('EX/MEM FORWARDING          : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('EX/MEM FORWARDING          : FAIL\n');

end


% ============================================================
% TEST 2
%
% MEM/WB -> EX forwarding
% ============================================================

result = hazard_control( ...
    3, ...
    2, ...
    5, ...
    false, ...
    false, ...
    "NONE", ...
    5, ...
    false, ...
    uint32(0), ...
    3, ...
    true, ...
    uint32(300));

if result.forwarding && ...
   result.rs1Forward && ...
   result.rs1Source == "MEM/WB" && ...
   result.rs1Value == uint32(300) && ...
   ~result.stall

    fprintf('MEM/WB FORWARDING          : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('MEM/WB FORWARDING          : FAIL\n');

end


% ============================================================
% TEST 3
%
% Load-use hazard.
%
% EX contains:
%       LW x1, ...
%
% ID reads:
%       x1
%
% Expected: stall.
% ============================================================

result = hazard_control( ...
    1, ...
    2, ...
    1, ...
    true, ...
    true, ...
    "LW", ...
    0, ...
    false, ...
    uint32(0), ...
    0, ...
    false, ...
    uint32(0));

if result.loadUseHazard && ...
   result.stall && ...
   ~result.pcWrite && ...
   ~result.ifIdWrite && ...
   result.idExFlush && ...
   result.insertBubble

    fprintf('LOAD-USE STALL             : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('LOAD-USE STALL             : FAIL\n');

end


% ============================================================
% TEST 4
%
% Load-use hazard through rs2.
% ============================================================

result = hazard_control( ...
    3, ...
    4, ...
    4, ...
    true, ...
    true, ...
    "LW", ...
    0, ...
    false, ...
    uint32(0), ...
    0, ...
    false, ...
    uint32(0));

if result.loadUseHazard && ...
   result.rs2LoadHazard && ...
   result.stall

    fprintf('RS2 LOAD-USE STALL        : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('RS2 LOAD-USE STALL        : FAIL\n');

end


% ============================================================
% TEST 5
%
% No dependency.
% No forwarding.
% No stall.
% ============================================================

result = hazard_control( ...
    1, ...
    2, ...
    3, ...
    false, ...
    false, ...
    "NONE", ...
    4, ...
    true, ...
    uint32(40), ...
    5, ...
    true, ...
    uint32(50));

if ~result.forwarding && ...
   ~result.loadUseHazard && ...
   ~result.stall && ...
   result.pcWrite && ...
   result.ifIdWrite

    fprintf('NORMAL PIPELINE FLOW       : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('NORMAL PIPELINE FLOW       : FAIL\n');

end


% ============================================================
% TEST 6
%
% Both forwarding operands.
% ============================================================

result = hazard_control( ...
    6, ...
    7, ...
    0, ...
    false, ...
    false, ...
    "NONE", ...
    6, ...
    true, ...
    uint32(600), ...
    7, ...
    true, ...
    uint32(700));

if result.forwarding && ...
   result.rs1Forward && ...
   result.rs2Forward && ...
   result.rs1Value == uint32(600) && ...
   result.rs2Value == uint32(700) && ...
   ~result.stall

    fprintf('DUAL FORWARDING            : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('DUAL FORWARDING            : FAIL\n');

end


% ============================================================
% TEST 7
%
% Load-use hazard must take priority over forwarding.
%
% Even if another forwarding source exists, the load dependency
% requires a stall.
% ============================================================

result = hazard_control( ...
    1, ...
    5, ...
    1, ...
    true, ...
    true, ...
    "LW", ...
    5, ...
    true, ...
    uint32(500), ...
    0, ...
    false, ...
    uint32(0));

if result.loadUseHazard && ...
   result.stall && ...
   ~result.pcWrite && ...
   ~result.ifIdWrite && ...
   result.idExFlush

    fprintf('STALL PRIORITY              : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('STALL PRIORITY              : FAIL\n');

end


% ============================================================
% TEST 8
%
% x0 must not forward or create a load-use hazard.
% ============================================================

result = hazard_control( ...
    0, ...
    0, ...
    0, ...
    true, ...
    true, ...
    "LW", ...
    0, ...
    true, ...
    uint32(999), ...
    0, ...
    true, ...
    uint32(888));

if ~result.forwarding && ...
   ~result.loadUseHazard && ...
   ~result.stall

    fprintf('x0 PROTECTION              : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('x0 PROTECTION              : FAIL\n');

end


% ============================================================
% TEST 9
%
% MEM/WB forwarding of a 32-bit value.
% ============================================================

value = uint32(hex2dec('FFFFFFFF'));

result = hazard_control( ...
    10, ...
    11, ...
    0, ...
    false, ...
    false, ...
    "NONE", ...
    0, ...
    false, ...
    uint32(0), ...
    10, ...
    true, ...
    value);

if result.rs1Forward && ...
   result.rs1Source == "MEM/WB" && ...
   result.rs1Value == value && ...
   isa(result.rs1Value,'uint32')

    fprintf('32-BIT FORWARDING          : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('32-BIT FORWARDING          : FAIL\n');

end


% ============================================================
% TEST 10
%
% Complete integrated stall control.
% ============================================================

result = hazard_control( ...
    12, ...
    13, ...
    12, ...
    true, ...
    true, ...
    "LW", ...
    0, ...
    false, ...
    uint32(0), ...
    0, ...
    false, ...
    uint32(0));

if result.loadUseHazard && ...
   result.stall && ...
   ~result.pcWrite && ...
   ~result.ifIdWrite && ...
   result.idExFlush && ...
   result.insertBubble

    fprintf('COMPLETE HAZARD CONTROL     : PASS\n');
    testsPassed = testsPassed + 1;

else

    fprintf('COMPLETE HAZARD CONTROL     : FAIL\n');

end


% ============================================================
% FINAL RESULTS
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('                  STAGE 19.6 RESULTS\n');
fprintf('============================================================\n');

fprintf('Tests passed : %d / %d\n', ...
    testsPassed,totalTests);

fprintf('============================================================\n');


% ============================================================
% PASS / FAIL
% ============================================================

if testsPassed == totalTests

    fprintf('\n');
    fprintf('********************************************\n');
    fprintf('       STAGE 19.6 PASSED!\n');
    fprintf('       FORWARDING + STALL INTEGRATED\n');
    fprintf('********************************************\n');

else

    fprintf('\n');
    fprintf('********************************************\n');
    fprintf('       STAGE 19.6 FAILED\n');
    fprintf('       CHECK RESULTS ABOVE\n');
    fprintf('********************************************\n');

end

end