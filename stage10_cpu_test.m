clc;
clear;

fprintf('\n');
fprintf('============================================================\n');
fprintf('          STAGE 10F - UNIFIED CPU TEST\n');
fprintf('============================================================\n');


% ============================================================
% PROGRAM
% ============================================================

program = {

    'ADDI x1, x0, 10'
    'ADDI x2, x0, 20'
    'ADD x3, x1, x2'
    'SUB x4, x3, x1'
    'AND x5, x3, x4'
    'OR x6, x3, x4'

};


% ============================================================
% RUN CPU
% ============================================================

[registers, pc, halted] = cpu(program,100);


% ============================================================
% DISPLAY FINAL REGISTER STATE
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('                FINAL CPU REGISTER STATE\n');
fprintf('============================================================\n');

for i = 1:7

    fprintf('x%d = %u\n', ...
        i-1, ...
        registers(i));

end


% ============================================================
% EXPECTED RESULTS
% ============================================================

expected = [
    0
    10
    20
    30
    20
    20
    30
];


actual = registers(1:7);


% ============================================================
% CHECK RESULTS
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('                    RESULT CHECK\n');
fprintf('============================================================\n');

fprintf('\nExpected:\n');
disp(expected);

fprintf('Actual:\n');
disp(actual);


if isequal(actual,expected) && ...
   pc == 24 && ...
   halted

    fprintf('\n');
    fprintf('********************************************\n');
    fprintf('          STAGE 10F PASSED!                \n');
    fprintf('       UNIFIED CPU WORKING                 \n');
    fprintf('********************************************\n');

else

    fprintf('\n');
    fprintf('STAGE 10F FAILED\n');

end


fprintf('\n');
fprintf('============================================================\n');