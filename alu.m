function result = alu(operation, A, B)

% =========================================================
% RISC-V 32-BIT ALU
% =========================================================
%
% Inputs:
%   operation : ADD, SUB, AND, OR, XOR
%   A         : 32-bit unsigned value
%   B         : 32-bit unsigned value
%
% Output:
%   result    : 32-bit unsigned value
%
% =========================================================


% Convert inputs to uint32

A = uint32(A);
B = uint32(B);


switch upper(operation)

    %% ====================================================
    % ADD
    % ====================================================

    case 'ADD'

        % Use modulo 2^32

        result = uint32( ...
            mod(double(A) + double(B), 2^32));


        %% ====================================================
        % SUB
        % ====================================================

    case 'SUB'

        % Use modulo 2^32

        result = uint32( ...
            mod(double(A) - double(B), 2^32));


        %% ====================================================
        % AND
        % ====================================================

    case 'AND'

        result = bitand(A, B);


        %% ====================================================
        % OR
        % ====================================================

    case 'OR'

        result = bitor(A, B);


        %% ====================================================
        % XOR
        % ====================================================

    case 'XOR'

        result = bitxor(A, B);


        %% ====================================================
        % UNKNOWN
        % ====================================================

    otherwise

        error( ...
            'Unknown ALU operation: %s', ...
            operation);

end

end