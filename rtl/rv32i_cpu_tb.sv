`timescale 1ns/1ps

module rv32i_cpu_tb;

    logic clk;
    logic reset;

    integer passed;
    integer total;

    // ------------------------------------------------------------
    // DUT
    // ------------------------------------------------------------
    rv32i_cpu dut (
        .clk   (clk),
        .reset (reset)
    );

    // ------------------------------------------------------------
    // Clock
    // ------------------------------------------------------------
    initial begin
        clk = 1'b0;
        forever #5 clk = ~clk;
    end

    // ------------------------------------------------------------
    // Helper: write instruction into instruction memory
    // ------------------------------------------------------------
    task write_instruction;
        input integer index;
        input [31:0] instruction;
        begin
            dut.instruction_memory[index] = instruction;
        end
    endtask

    // ------------------------------------------------------------
    // Helper: check register
    // ------------------------------------------------------------
    task check_register;
        input [4:0]  reg_num;
        input [31:0] expected;
        input [255:0] name;

        reg [31:0] actual;

        begin
            actual = dut.rf.registers[reg_num];

            total = total + 1;

            if (actual === expected) begin
                passed = passed + 1;
                $display("PASS: %30s x%0d = %0d",
                         name, reg_num, actual);
            end
            else begin
                $display("FAIL: %30s x%0d Expected=%0d Got=%0d",
                         name, reg_num, expected, actual);
            end
        end
    endtask

    // ------------------------------------------------------------
    // Helper: check memory
    // ------------------------------------------------------------
    task check_memory;
        input integer address;
        input [31:0] expected;
        input [255:0] name;

        reg [31:0] actual;

        begin
            actual = dut.data_memory[address];

            total = total + 1;

            if (actual === expected) begin
                passed = passed + 1;
                $display("PASS: %s", name);
            end
            else begin
                $display("FAIL: %s Expected=%0d Got=%0d",
                         name, expected, actual);
            end
        end
    endtask

    // ------------------------------------------------------------
    // Main test
    // ------------------------------------------------------------
    initial begin

        passed = 0;
        total  = 0;

        $display("==============================================");
        $display("STAGE 24.9 - RV32I REGRESSION TEST");
        $display("==============================================");
        $display("");

        // --------------------------------------------------------
        // Reset
        // --------------------------------------------------------
        reset = 1'b1;

        #20;

        reset = 1'b0;

        // --------------------------------------------------------
        // Clear instruction memory
        // --------------------------------------------------------
        for (integer i = 0; i < 256; i = i + 1)
            dut.instruction_memory[i] = 32'h00000000;

        // --------------------------------------------------------
        // Clear data memory
        // --------------------------------------------------------
        for (integer i = 0; i < 256; i = i + 1)
            dut.data_memory[i] = 32'h00000000;

        // ========================================================
        // PROGRAM
        // ========================================================
        //
        // Instruction indexes / PC:
        //
        //  0 : ADDI x1, x0, 10
        //  1 : ADDI x2, x0, 20
        //  2 : ADD  x3, x1, x2
        //  3 : SUB  x4, x1, x2
        //  4 : AND  x5, x1, x2
        //  5 : OR   x6, x1, x2
        //  6 : XOR  x7, x1, x2
        //  7 : ADDI x8, x0, 100
        //  8 : SW   x3, 0(x8)
        //  9 : LW   x9, 0(x8)
        // 10 : ADD  x10, x9, x1
        //
        // 11 : BEQ  x10, x10, +8
        // 12 : ADDI x11, x0, 99       <-- flushed
        // 13 : ADDI x12, x0, 55       <-- target
        //
        // 14 : BNE  x1, x2, +8
        // 15 : ADDI x13, x0, 99       <-- flushed
        // 16 : ADDI x14, x0, 66       <-- target
        //
        // 17 : JAL  x15, +8
        // 18 : ADDI x19, x0, 99       <-- flushed
        // 19 : ADDI x16, x0, 100      <-- target
        //
        // 20 : JALR x17, x16, 0
        // 21 : ADDI x18, x0, 99       <-- flushed
        // 22 : ADDI x19, x0, 88       <-- flushed
        //
        // Target address = 100
        // 100 / 4 = instruction index 25
        //
        // 25 : ADDI x20, x0, 123
        //
        // ========================================================

        // --------------------------------------------------------
        // 0: ADDI x1, x0, 10
        // --------------------------------------------------------
        write_instruction(
            0,
            32'h00A00093
        );

        // --------------------------------------------------------
        // 1: ADDI x2, x0, 20
        // --------------------------------------------------------
        write_instruction(
            1,
            32'h01400113
        );

        // --------------------------------------------------------
        // 2: ADD x3, x1, x2
        // --------------------------------------------------------
        write_instruction(
            2,
            32'h002081B3
        );

        // --------------------------------------------------------
        // 3: SUB x4, x1, x2
        // Result = -10 = 0xFFFFFFF6
        // --------------------------------------------------------
        write_instruction(
            3,
            32'h40208233
        );

        // --------------------------------------------------------
        // 4: AND x5, x1, x2
        // --------------------------------------------------------
        write_instruction(
            4,
            32'h0020F2B3
        );

        // --------------------------------------------------------
        // 5: OR x6, x1, x2
        // --------------------------------------------------------
        write_instruction(
            5,
            32'h0020E333
        );

        // --------------------------------------------------------
        // 6: XOR x7, x1, x2
        // --------------------------------------------------------
        write_instruction(
            6,
            32'h0020C3B3
        );

        // --------------------------------------------------------
        // 7: ADDI x8, x0, 100
        // --------------------------------------------------------
        write_instruction(
            7,
            32'h06400413
        );

        // --------------------------------------------------------
        // 8: SW x3, 0(x8)
        // --------------------------------------------------------
        write_instruction(
            8,
            32'h00342023
        );

        // --------------------------------------------------------
        // 9: LW x9, 0(x8)
        // --------------------------------------------------------
        write_instruction(
            9,
            32'h00042483
        );

        // --------------------------------------------------------
        // 10: ADD x10, x9, x1
        // --------------------------------------------------------
        write_instruction(
            10,
            32'h00148533
        );

        // --------------------------------------------------------
        // 11: BEQ x10, x10, +8
        // Skip instruction 12
        // --------------------------------------------------------
        write_instruction(
            11,
            32'h00A50463
        );

        // --------------------------------------------------------
        // 12: ADDI x11, x0, 99
        // Must be flushed
        // --------------------------------------------------------
        write_instruction(
            12,
            32'h06300593
        );

        // --------------------------------------------------------
        // 13: ADDI x12, x0, 55
        // --------------------------------------------------------
        write_instruction(
            13,
            32'h03700613
        );

        // --------------------------------------------------------
        // 14: BNE x1, x2, +8
        // Skip instruction 15
        // --------------------------------------------------------
        write_instruction(
            14,
            32'h00209463
        );

        // --------------------------------------------------------
        // 15: ADDI x13, x0, 99
        // Must be flushed
        // --------------------------------------------------------
        write_instruction(
            15,
            32'h06300693
        );

        // --------------------------------------------------------
        // 16: ADDI x14, x0, 66
        // --------------------------------------------------------
        write_instruction(
            16,
            32'h04200713
        );

        // --------------------------------------------------------
        // 17: JAL x15, +8
        //
        // PC = 68
        // Link = 72
        // Target = 76
        // --------------------------------------------------------
        write_instruction(
            17,
            32'h008007EF
        );

        // --------------------------------------------------------
        // 18: ADDI x19, x0, 99
        // Must be flushed
        // --------------------------------------------------------
        write_instruction(
            18,
            32'h06300993
        );

        // --------------------------------------------------------
        // 19: ADDI x16, x0, 100
        // --------------------------------------------------------
        write_instruction(
            19,
            32'h06400813
        );

        // --------------------------------------------------------
        // 20: JALR x17, x16, 0
        //
        // PC = 80
        // Link = 84
        // Target = x16 + 0 = 100
        // --------------------------------------------------------
        write_instruction(
            20,
            32'h000803E7
        );

        // --------------------------------------------------------
        // 21: ADDI x18, x0, 99
        // Must be flushed
        // --------------------------------------------------------
        write_instruction(
            21,
            32'h06300913
        );

        // --------------------------------------------------------
        // 22: ADDI x19, x0, 88
        // Must be flushed
        // --------------------------------------------------------
        write_instruction(
            22,
            32'h05800993
        );

        // --------------------------------------------------------
        // 23: NOP
        // --------------------------------------------------------
        write_instruction(
            23,
            32'h00000013
        );

        // --------------------------------------------------------
        // 24: NOP
        // --------------------------------------------------------
        write_instruction(
            24,
            32'h00000013
        );

        // --------------------------------------------------------
        // 25: ADDI x20, x0, 123
        // Target of JALR
        // --------------------------------------------------------
        write_instruction(
            25,
            32'h07B00A13
        );

        // --------------------------------------------------------
        // 26: NOP
        // --------------------------------------------------------
        write_instruction(
            26,
            32'h00000013
        );

        // --------------------------------------------------------
        // 27: NOP
        // --------------------------------------------------------
        write_instruction(
            27,
            32'h00000013
        );

        // --------------------------------------------------------
        // Run CPU
        // --------------------------------------------------------
        #1000;

        // ========================================================
        // REGRESSION RESULTS
        // ========================================================

        $display("");
        $display("==============================================");
        $display("REGRESSION RESULTS");
        $display("==============================================");

        // --------------------------------------------------------
        // Arithmetic
        // --------------------------------------------------------

        check_register(
            5'd1,
            32'd10,
            "ADDI x1 = 10"
        );

        check_register(
            5'd2,
            32'd20,
            "ADDI x2 = 20"
        );

        check_register(
            5'd3,
            32'd30,
            "ADD x3 = 30"
        );

        check_register(
            5'd4,
            32'hFFFFFFF6,
            "SUB x4 = 4294967286"
        );

        check_register(
            5'd5,
            32'd0,
            "AND x5 = 0"
        );

        check_register(
            5'd6,
            32'd30,
            "OR x6 = 30"
        );

        check_register(
            5'd7,
            32'd30,
            "XOR x7 = 30"
        );

        // --------------------------------------------------------
        // Load / Store
        // --------------------------------------------------------

        check_register(
            5'd9,
            32'd30,
            "LW x9 = 30"
        );

        check_memory(
            100,
            32'd30,
            "SW memory[100]"
        );

        // --------------------------------------------------------
        // Dependent operation
        // --------------------------------------------------------

        check_register(
            5'd10,
            32'd40,
            "Dependent ADD x10 = 40"
        );

        // --------------------------------------------------------
        // Branch tests
        // --------------------------------------------------------

        check_register(
            5'd11,
            32'd0,
            "BEQ flush x11 = 0"
        );

        check_register(
            5'd12,
            32'd55,
            "BEQ target x12 = 55"
        );

        check_register(
            5'd13,
            32'd0,
            "BNE flush x13 = 0"
        );

        check_register(
            5'd14,
            32'd66,
            "BNE target x14 = 66"
        );

        // --------------------------------------------------------
        // JAL
        // --------------------------------------------------------

        check_register(
            5'd15,
            32'd72,
            "JAL link x15 = 72"
        );

        check_register(
            5'd16,
            32'd100,
            "JAL target x16 = 100"
        );

        // --------------------------------------------------------
        // JALR
        //
        // JALR is at PC = 80
        // Therefore link address = 80 + 4 = 84
        // --------------------------------------------------------

        check_register(
            5'd17,
            32'd84,
            "JALR link x17 = 84"
        );

        check_register(
            5'd20,
            32'd123,
            "JALR target x20 = 123"
        );

        check_register(
            5'd18,
            32'd0,
            "JALR flush 1 x18 = 0"
        );

        check_register(
            5'd19,
            32'd0,
            "JALR flush 2 x19 = 0"
        );

        // --------------------------------------------------------
        // x0 must always remain zero
        // --------------------------------------------------------

        check_register(
            5'd0,
            32'd0,
            "x0 x0 = 0"
        );

        // ========================================================
        // SUMMARY
        // ========================================================

        $display("");
        $display("==============================================");
        $display("STAGE 24.9 SUMMARY");
        $display("==============================================");

        $display("");
        $display("Tests passed : %0d / %0d", passed, total);

        if (passed == total) begin
            $display("");
            $display("STAGE 24.9 PASSED!");
        end
        else begin
            $display("");
            $display("STAGE 24.9 FAILED");
        end

        $display("==============================================");

        #20;

        $finish;
    end

endmodule