function next = mem_wb_register( ...
    valid, ...
    pc, ...
    opcode, ...
    aluResult, ...
    memoryData, ...
    rd, ...
    memoryToReg, ...
    regWrite)

% =============================================================
% RISC-V PIPELINE
%
% STAGE 18.9
% MEM/WB PIPELINE REGISTER
%
% Transfers information from:
%
%       MEM  -->  WB
%
% =============================================================

% =============================================================
% INPUT VALIDATION
% =============================================================

if nargin < 8
    error('mem_wb_register requires 8 inputs.');
end


% =============================================================
% CREATE MEM/WB REGISTER
% =============================================================

next = struct();


% =============================================================
% VALID
% =============================================================

next.valid = logical(valid);


% =============================================================
% PROGRAM COUNTER
% =============================================================

next.pc = uint32(pc);


% =============================================================
% OPCODE
% =============================================================

next.opcode = string(opcode);


% =============================================================
% ALU RESULT
% =============================================================

next.aluResult = uint32(aluResult);


% =============================================================
% MEMORY DATA
% =============================================================

next.memoryData = uint32(memoryData);


% =============================================================
% DESTINATION REGISTER
% =============================================================

if rd < 0 || rd > 31 || floor(rd) ~= rd

    error('Invalid destination register: %d',rd);

end

next.rd = rd;


% =============================================================
% MEMORY-TO-REGISTER CONTROL
% =============================================================

next.memoryToReg = logical(memoryToReg);


% =============================================================
% REGISTER WRITE CONTROL
% =============================================================

next.regWrite = logical(regWrite);


% =============================================================
% FINAL MEM/WB REGISTER
% =============================================================

end