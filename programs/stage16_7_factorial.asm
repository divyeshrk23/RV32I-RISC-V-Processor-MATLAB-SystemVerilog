# ============================================================
# STAGE 16.7 - FACTORIAL + MEMORY STORE
# ============================================================

# x1 = current number
# x2 = factorial result
# x3 = multiplication counter
# x4 = temporary multiplication result
# x5 = constant 1
# x6 = temporary register

# ============================================================
# INITIALIZATION
# ============================================================

# Current number = 5
ADDI x1, x0, 5

# Result = 1
ADDI x2, x0, 1

# Constant 1
ADDI x5, x0, 1

# ============================================================
# OUTER LOOP
# ============================================================

# Temporary calculation
ADDI x6, x1, -1

# If x1 <= 1, finish
#
# Current PC = 16
# SW instruction is at PC = 52
#
# 52 - 16 = 36
#
BGE x5, x1, 36


# ============================================================
# MULTIPLICATION SETUP
# ============================================================

# x4 = 0
ADDI x4, x0, 0

# x3 = current number
ADD x3, x1, x0


# ============================================================
# MULTIPLICATION LOOP
#
# x4 = x4 + x2
# repeated x3 times
# ============================================================

ADD x4, x4, x2

ADDI x3, x3, -1

BGE x3, x5, -8


# ============================================================
# UPDATE FACTORIAL RESULT
# ============================================================

ADD x2, x4, x0


# ============================================================
# DECREMENT CURRENT NUMBER
# ============================================================

ADDI x1, x1, -1


# ============================================================
# RETURN TO OUTER LOOP
# ============================================================

JAL x0, -32


# ============================================================
# STORE FINAL RESULT
# ============================================================

# 5! = 120
#
# Store at memory address 20

SW x2, 20(x0)