# ============================================================
# STAGE 16.12 - GCD USING EUCLIDEAN ALGORITHM
# ============================================================
#
# Calculate:
#
# GCD(48, 18) = 6
#
# Algorithm:
#
# while a != b
#     if a < b
#         b = b - a
#     else
#         a = a - b
#
# Result:
#     a = b = 6
#
# Memory:
#
# MEM[0] = 48
# MEM[4] = 18
# MEM[8] = 6
#
# Registers:
#
# x1 = a
# x2 = b
# x3 = result
#
# ============================================================


# ============================================================
# LOAD INPUTS
# ============================================================

LW x1, 0(x0)
LW x2, 4(x0)


# ============================================================
# GCD LOOP
# ============================================================

# PC = 8
#
# If a == b:
#     jump to result at PC 32
#
BEQ x1, x2, 24


# PC = 12
#
# If a < b:
#     jump to b = b - a at PC 24
#
BLT x1, x2, 12


# ============================================================
# a = a - b
# ============================================================

# PC = 16

SUB x1, x1, x2


# ============================================================
# Repeat GCD loop
# ============================================================

# PC = 20
# Jump back to PC 8

JAL x0, -12


# ============================================================
# b = b - a
# ============================================================

# PC = 24

SUB x2, x2, x1


# ============================================================
# Repeat GCD loop
# ============================================================

# PC = 28
# Jump back to PC 8

JAL x0, -20


# ============================================================
# RESULT
# ============================================================

# PC = 32

ADD x3, x1, x0


# ============================================================
# STORE RESULT
# ============================================================

# PC = 36

SW x3, 8(x0)


# ============================================================
# END
# ============================================================

# PC = 40
# Jump to PC 44, outside the program.
# CPU fetches 0 -> END.

JAL x0, 4