# ============================================================
# STAGE 16.8 - ARRAY + FUNCTION + CONDITIONAL INTEGRATION
# ============================================================

# Memory:
#
# MEM[0]  = 10
# MEM[4]  = 20
# MEM[8]  = 30
# MEM[12] = 40
#
# Sum = 100
#
# Function:
#   if sum >= 100
#       result = sum + 50
#
# Expected:
#
# x3      = 100
# x6      = 150
# MEM[16] = 150
#
# ============================================================


# ============================================================
# ARRAY INITIALIZATION
# ============================================================

ADDI x1, x0, 0
ADDI x2, x0, 0
ADDI x3, x0, 0
ADDI x5, x0, 4


# ============================================================
# ARRAY LOOP
# ============================================================

LW x4, 0(x1)

ADD x3, x3, x4

ADDI x1, x1, 4

ADDI x2, x2, 1

BLT x2, x5, -16


# ============================================================
# FUNCTION CALL
# ============================================================

# PC = 36
# Function starts at PC = 48
#
# 48 - 36 = 12
#
# x7 = return address 40

JAL x7, 12


# ============================================================
# RETURN POINT
# ============================================================

# PC = 40

SW x6, 16(x0)

# Skip function and terminate
#
# PC = 44
# Target = 72
#
# 72 - 44 = 28

JAL x0, 28


# ============================================================
# FUNCTION
# ============================================================

# PC = 48

ADDI x8, x0, 100


# ============================================================
# CONDITIONAL
# ============================================================

# PC = 52
#
# True branch is PC = 64
#
# 64 - 52 = 12

BGE x3, x8, 12


# ============================================================
# FALSE BRANCH
# ============================================================

# PC = 56

ADD x6, x3, x0

# Skip true branch
#
# PC = 60
# Target = 68
#
# 68 - 60 = 8

JAL x0, 8


# ============================================================
# TRUE BRANCH
# ============================================================

# PC = 64

ADDI x6, x3, 50


# ============================================================
# FUNCTION RETURN
# ============================================================

# PC = 68

JALR x0, 0(x7)