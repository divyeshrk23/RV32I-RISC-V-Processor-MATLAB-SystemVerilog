# ============================================================
# STAGE 16.14 - POWER / EXPONENTIATION
# ============================================================
#
# Calculate:
#
#   2^5 = 32
#   3^4 = 81
#   5^3 = 125
#
# Results:
#
#   MEM[0]  = 32
#   MEM[4]  = 81
#   MEM[8]  = 125
#
# Multiplication is implemented using repeated addition.
#
# ============================================================


# ============================================================
# 2^5
# ============================================================

# x1 = base = 2
ADDI x1, x0, 2

# x2 = exponent = 5
ADDI x2, x0, 5

# x3 = result = 1
ADDI x3, x0, 1


# ============================================================
# POWER LOOP
# ============================================================

# x4 = counter
ADD x4, x2, x0

# If counter == 0 -> DONE
BEQ x4, x0, 52


# ============================================================
# MULTIPLICATION
#
# x3 = x3 * x1
# ============================================================

ADD x5, x0, x0
ADD x6, x3, x0

# If multiplier == 0
BEQ x1, x0, 28

ADD x5, x5, x6
ADDI x1, x1, -1
BNE x1, x0, -12

ADD x3, x5, x0

# Restore base = 2
ADDI x1, x0, 2

ADDI x4, x4, -1
BNE x4, x0, -36

SW x3, 0(x0)

# ============================================================
# 3^4
# ============================================================

ADDI x1, x0, 3
ADDI x2, x0, 4
ADDI x3, x0, 1

# Direct repeated multiplication using addition

ADD x4, x2, x0

BEQ x4, x0, 52

ADD x5, x0, x0
ADD x6, x3, x0

ADD x5, x5, x6
ADDI x1, x1, -1
BNE x1, x0, -12

ADD x3, x5, x0

ADDI x1, x0, 3
ADDI x4, x4, -1
BNE x4, x0, -36

SW x3, 4(x0)


# ============================================================
# 5^3
# ============================================================

ADDI x1, x0, 5
ADDI x2, x0, 3
ADDI x3, x0, 1

ADD x4, x2, x0

BEQ x4, x0, 52

ADD x5, x0, x0
ADD x6, x3, x0

ADD x5, x5, x6
ADDI x1, x1, -1
BNE x1, x0, -12

ADD x3, x5, x0

ADDI x1, x0, 5
ADDI x4, x4, -1
BNE x4, x0, -36

SW x3, 8(x0)


# ============================================================
# END
# ============================================================

JAL x0, 4