# ============================================================
# STAGE 16.5 - FUNCTION CALL + RETURN
# ============================================================

# ------------------------------------------------------------
# Main program
#
# x1 = 10
# x2 = 20
#
# Call function.
#
# Function calculates:
# x3 = x1 + x2
#
# Return to main.
# ------------------------------------------------------------

ADDI x1, x0, 10
ADDI x2, x0, 20

# Call function
# x5 receives return address
JAL x5, 12

# ------------------------------------------------------------
# Return point
# ------------------------------------------------------------

# Function result should be 30
# Add 5 to result
ADDI x3, x3, 5

# Skip over function body
JAL x0, 16


# ============================================================
# FUNCTION
# ============================================================

# x3 = x1 + x2
ADD x3, x1, x2

# Return to caller
JALR x0, 0(x5)