# ============================================================
# STAGE 16.10 - ARRAY SORTING
# ============================================================
#
# Bubble-sort style ascending sort
#
# Initial:
#   [25, 7, 42, 18, 33]
#
# Expected:
#   [7, 18, 25, 33, 42]
#
# x2 = outer-loop counter
# x3 = inner-loop counter
# x4 = current array pointer
# x5 = current element
# x6 = next element
#
# ============================================================


# ============================================================
# INITIALIZATION
# ============================================================

# x2 = number of inner comparisons
ADDI x2, x0, 4


# ============================================================
# OUTER LOOP
# ============================================================

# x3 = inner-loop counter
ADD x3, x2, x0

# x4 = array pointer
ADDI x4, x0, 0


# ============================================================
# INNER LOOP
# ============================================================

# ------------------------------------------------------------
# Load current element
# ------------------------------------------------------------

LW x5, 0(x4)

# ------------------------------------------------------------
# Load next element
# ------------------------------------------------------------

LW x6, 4(x4)


# ============================================================
# COMPARE
# ============================================================

# If next < current:
#   branch to swap
#
# Current PC = 24
# Swap starts at PC = 32
#
# 32 - 24 = 8

BLT x6, x5, 8


# ============================================================
# NO SWAP
# ============================================================

# Skip swap.
#
# PC = 28
# Continue at PC = 40
#
# 40 - 28 = 12

JAL x0, 12


# ============================================================
# SWAP
# ============================================================

# PC = 32

# current = next
SW x6, 0(x4)

# next = current
SW x5, 4(x4)


# ============================================================
# NEXT INNER ELEMENT
# ============================================================

# PC = 40

ADDI x4, x4, 4

ADDI x3, x3, -1

# Continue inner loop
#
# Current PC = 48
# Inner-loop start = 16
#
# 16 - 48 = -32

BNE x3, x0, -32


# ============================================================
# NEXT OUTER PASS
# ============================================================

# PC = 52

ADDI x2, x2, -1

# Continue outer loop
#
# Current PC = 56
# Outer-loop start = 8
#
# 8 - 56 = -48

BNE x2, x0, -48


# ============================================================
# END
# ============================================================

# PC = 60
# Jump to PC = 80
#
# 80 - 60 = 20

JAL x0, 20