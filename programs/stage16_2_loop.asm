# ============================================================
# STAGE 16.2 - LOOP + BRANCH INTEGRATION PROGRAM
# ============================================================

# x1 = loop counter
# x2 = loop limit
# x3 = accumulated sum

ADDI x1, x0, 1
ADDI x2, x0, 6
ADDI x3, x0, 0

# ------------------------------------------------------------
# LOOP
# ------------------------------------------------------------

ADD x3, x3, x1
ADDI x1, x1, 1
BLT x1, x2, -8

# ------------------------------------------------------------
# After loop:
# x3 = 1 + 2 + 3 + 4 + 5 = 15
# x1 = 6
# ------------------------------------------------------------